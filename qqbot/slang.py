def pick(day: date | None = None, count: int = 10) -> list[tuple[str, str, str]]:
    """每天换一批，同一天内稳定（不要每条消息都换，模型会精神分裂）。"""
    today = day or date.today()
    seed = today.year * 10000 + today.month * 100 + today.day
    rng = random.Random(seed)
    items = list(ITEMS)
    rng.shuffle(items)
    return items[: max(1, min(count, len(items)))]


def block(day: date | None = None, count: int = 10) -> str:
    """进 system prompt 的那一段。"""
    lines = ["【今天的口头语】（用得上就用，用不上就算了；一天最多三四次，别硬凑）"]
    for word, example, when in pick(day, count):
        lines.append(f"- {word}：「{example}」——{when}")
    lines.append("插话用的词：" + "、".join(FILLERS) + "（自然带出来，不要每句都加）")
    lines.append("这些别说，过时了：" + "、".join(BANNED))
    return "\n".join(lines)
