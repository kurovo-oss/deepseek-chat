"""网络用语的**词义表**：她听得懂，但自己不说。

和之前删掉的那版（每天抽 10 条让她用）不一样：那版让说话变油了。
这版只给意思，明确写"自己别用"。他发"已老实求放过"，她要知道这是认输，
接一句"怎么啦，没词了吧"就行，不用跟着说"我已老实"。

要加词就往 `GLOSSARY` 里加一行，一行一个：词=意思。
"""

from __future__ import annotations

GLOSSARY: tuple[tuple[str, str], ...] = (
    ("已老实", "认输、求放过"),
    ("破防", "被戳到痛处或被夸到"),
    ("绷不住", "忍不住笑"),
    ("典", "典型、带讽刺"),
    ("急了", "着急了，互怼的时候用"),
    ("尊嘟假嘟", "真的假的"),
    ("栓Q", "无奈地道谢"),
    ("偷感很重", "偷偷摸摸、心虚"),
    ("班味", "上完班的疲惫感"),
    ("松弛感", "不紧绷、不焦虑"),
    ("city不city", "洋不洋气"),
    ("电子榨菜", "下饭的视频"),
    ("显眼包", "爱出风头的人"),
    ("哈基米", "可爱的小东西"),
    ("水灵灵地", "当副词用，接一个动作"),
    ("属于是", "可以说是"),
)

# 已经过时的，他要是用大概率是在反讽
DATED: tuple[str, ...] = ("绝绝子", "yyds", "干饭人", "skr", "awsl", "u1s1")


def block() -> str:
    """进 system prompt 的那一段。只给意思，不给"怎么用"。"""
    lines = ["【他可能会用的网络用语】（你听得懂就行，自己说话别用这些）"]
    lines.append("；".join(f"{word}={meaning}" for word, meaning in GLOSSARY))
    lines.append(
        "他用了你就当正常话说，接内容、别复读那个词。"
        "过时的（" + "、".join(DATED) + "）他要是用，多半是在逗你。"
    )
    return "\n".join(lines)
